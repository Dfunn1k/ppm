import "./lib/install";   // escucha desde el arranque si el navegador permite instalar PPM

import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { BrowserRouter } from "react-router";

import { App } from "./App";
import { ViewTransitions } from "./lib/transitions";

const queryClient = new QueryClient({
  defaultOptions: { queries: { retry: 1, refetchOnWindowFocus: false } },
});

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <BrowserRouter>
        <ViewTransitions />
        <App />
      </BrowserRouter>
    </QueryClientProvider>
  </StrictMode>,
);

// El service worker guarda los archivos de la app en el equipo (solo en producción)
if (import.meta.env.PROD && "serviceWorker" in navigator) {
  window.addEventListener("load", () => { navigator.serviceWorker.register("/sw.js").catch(() => {}); });
}
